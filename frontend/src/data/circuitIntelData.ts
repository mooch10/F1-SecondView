function normalizeTerm(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\\u0300-\\u036f]/g, '')
    .replace(/[\\s-]+/g, '_')
    .replace(/[^a-z0-9_]/g, '');
}

export const getCircuitIntel = (circuitIdOrName?: string): CircuitIntel => {
  if (!circuitIdOrName) return CIRCUIT_INTEL_CATALOG['madrid'];
  const clean = normalizeTerm(circuitIdOrName);

  // 1. Direct Catalog Key Match
  if (CIRCUIT_INTEL_CATALOG[clean]) {
    return CIRCUIT_INTEL_CATALOG[clean];
  }

  // 2. Exact Alias Match
  if (INTEL_ALIASES[clean] && CIRCUIT_INTEL_CATALOG[INTEL_ALIASES[clean]]) {
    return CIRCUIT_INTEL_CATALOG[INTEL_ALIASES[clean]];
  }

  // 3. Substring / Token Alias Match (Sort by longest alias first to prevent short prefix collisions)
  const sortedAliases = Object.keys(INTEL_ALIASES).sort((a, b) => b.length - a.length);
  for (const alias of sortedAliases) {
    if (clean.includes(alias)) {
      const targetId = INTEL_ALIASES[alias];
      if (CIRCUIT_INTEL_CATALOG[targetId]) {
        return CIRCUIT_INTEL_CATALOG[targetId];
      }
    }
  }

  // 4. Match against circuit fields (name, country, city, officialGpName)
  for (const data of Object.values(CIRCUIT_INTEL_CATALOG)) {
    const normName = normalizeTerm(data.name);
    const normCountry = normalizeTerm(data.country);
    const normCity = normalizeTerm(data.city);
    const normGp = normalizeTerm(data.officialGpName);

    if (
      clean.includes(normName) ||
      normName.includes(clean) ||
      clean.includes(normCountry) ||
      clean.includes(normCity) ||
      clean.includes(normGp)
    ) {
      return data;
    }
  }

  return CIRCUIT_INTEL_CATALOG['madrid'];
};

